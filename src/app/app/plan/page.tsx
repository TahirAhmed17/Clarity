import type { Metadata } from "next";
import { Suspense } from "react";
import { EvidenceList } from "@/components/features/evidence-list";
import { PostButton } from "@/components/features/post-button";
import { Badge, Card, Disclaimer, EmptyState, PageHeader, ProvenanceTag } from "@/components/ui/primitives";
import type { PlanActionItem } from "@/lib/domain";
import { evidenceRefs } from "@/server/evidence/refs";
import { loadPageData } from "@/server/session";

export const metadata: Metadata = { title: "Daily plan" };

const CATEGORY: Record<PlanActionItem["category"], string> = {
  movement: "Movement",
  nutrition: "Nutrition",
  sleep: "Sleep",
  supplement: "Supplement info",
  professional: "Professional",
  other: "General",
};

function ActionCard({ planId, action, primary }: { planId: string; action: PlanActionItem; primary?: boolean }) {
  return (
    <Card className={primary ? "bg-gradient-to-br from-mint-soft via-white to-mist-soft" : ""}>
      <div className="mb-2 flex flex-wrap items-center gap-2">
        {primary && <Badge tone="teal">Your next move</Badge>}
        <Badge tone="neutral">{CATEGORY[action.category]}</Badge>
        <ProvenanceTag kind="calculated" />
        {action.status !== "pending" && <Badge tone={action.status === "completed" ? "lime" : "neutral"}>{action.status === "completed" ? "Done" : "Skipped"}</Badge>}
      </div>
      <h3 className={primary ? "font-display text-2xl text-ink" : "font-semibold text-ink"}>{action.title}</h3>
      <p className="mt-1 text-sm text-ink-soft">{action.detail}</p>
      {action.reasons && action.reasons.length > 0 && <p className="mt-2 text-xs text-ink-faint">Why this: {action.reasons.join("; ")}.</p>}
      <div className="mt-3">
        <EvidenceList items={evidenceRefs(action.evidenceChunkIds)} />
      </div>
      {action.status === "pending" && (
        <div className="mt-4 flex flex-wrap gap-2">
          <PostButton url="/api/plan/actions" body={{ planId, actionId: action.id, outcome: "completed" }} label="Mark done" variant="soft" />
          <PostButton url="/api/plan/actions" body={{ planId, actionId: action.id, outcome: "skipped" }} label="Skip" variant="secondary" />
        </div>
      )}
    </Card>
  );
}

async function PlanContent() {
  const { repo, profileId } = await loadPageData();
  const [plan, history] = await Promise.all([repo.getActivePlan(profileId), repo.listActionHistory(profileId)]);
  if (!plan) {
    return (
      <EmptyState title="No plan yet" action={<PostButton url="/api/plan" label="Create my plan" pendingLabel="Building your plan…" />}>
        Clarity picks one next move from your results, goals, symptoms and wearable data, plus up to three small supporting actions.
      </EmptyState>
    );
  }
  return (
    <div className="space-y-5">
      <div className="flex flex-wrap items-center justify-between gap-3">
        <p className="text-sm text-ink-soft">
          Plan for {plan.planDate} · generated by {plan.generatedBy}
        </p>
        <PostButton url="/api/plan" label="Refresh plan" variant="secondary" pendingLabel="Refreshing…" />
      </div>
      <ActionCard planId={plan.id} action={plan.primaryAction} primary />
      <div className="grid gap-4 md:grid-cols-3">
        {plan.supportingActions.map((a) => (
          <ActionCard key={a.id} planId={plan.id} action={a} />
        ))}
      </div>
      {history.length > 0 && (
        <Card>
          <h2 className="mb-2 font-semibold">Recent activity</h2>
          <p className="mb-3 text-xs text-ink-faint">Skipped actions are de-prioritised next time; done actions stay in rotation.</p>
          <ul className="divide-y divide-line text-sm">
            {history.slice(0, 8).map((h) => (
              <li key={h.id} className="flex justify-between gap-3 py-2">
                <span>{h.actionTitle}</span>
                <span className="text-ink-faint">
                  {h.outcome} · {h.createdAt.slice(0, 10)}
                </span>
              </li>
            ))}
          </ul>
        </Card>
      )}
      <Disclaimer />
    </div>
  );
}

export default function PlanPage() {
  return (
    <div>
      <PageHeader title="Your plan">One clear next move, with a few small supporting steps. Each one shows why it was chosen and the evidence behind it.</PageHeader>
      <Suspense fallback={<p className="text-ink-soft">Loading your plan…</p>}>
        <PlanContent />
      </Suspense>
    </div>
  );
}
